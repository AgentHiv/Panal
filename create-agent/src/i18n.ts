export type Lang = (typeof LANGS)[number]['code'];

export const LANG_CODES = LANGS.map((l) => l.code) as readonly Lang[];

export function isLang(v: string): v is Lang {
  return (LANG_CODES as readonly string[]).includes(v);
}

